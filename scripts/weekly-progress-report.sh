#!/bin/bash
# 周进度报告生成脚本
# 用途：自动生成每周进度报告
# 使用：./scripts/weekly-progress-report.sh

set -e

# 颜色定义
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m'

# 获取当前周数和日期范围
CURRENT_WEEK=$(date +%V)
YEAR=$(date +%Y)
MONDAY=$(date -d "monday" '+%Y-%m-%d')
SUNDAY=$(date -d "sunday" '+%Y-%m-%d')

echo -e "${BLUE}📊 第${CURRENT_WEEK}周进度报告生成${NC}"
echo "========================================"
echo "周次: 第${CURRENT_WEEK}周 (${YEAR})"
echo "日期范围: ${MONDAY} - ${SUNDAY}"
echo ""

# 创建报告目录
REPORT_DIR="docs/weekly-reports"
mkdir -p "$REPORT_DIR"

REPORT_FILE="${REPORT_DIR}/week-${CURRENT_WEEK}-${YEAR}.md"

# 生成报告
cat > "$REPORT_FILE" << EOF
# 第${CURRENT_WEEK}周进度报告

**报告日期**: $(date '+%Y-%m-%d %H:%M:%S')
**周次**: 第${CURRENT_WEEK}周 (${YEAR})
